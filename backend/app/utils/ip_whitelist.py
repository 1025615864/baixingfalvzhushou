def validate_ip_in_whitelist(client_ip: str, whitelist: List[str]) -> bool:
    """
    验证IP是否在白名单范围内
    
    Args:
        client_ip: 客户端IP地址
        whitelist: IP白名单列表（支持CIDR格式，如 "192.168.1.0/24"）
    
    Returns:
        bool: IP是否在白名单中
    """
    if not client_ip:
        return False
    
    try:
        client_addr = ipaddress.ip_address(client_ip)
        
        for allowed in whitelist:
            try:
                if "/" in allowed:
                    # CIDR格式
                    network = ipaddress.ip_network(allowed, strict=False)
                    if client_addr in network:
                        return True
                else:
                    # 单个IP
                    if client_addr == ipaddress.ip_address(allowed):
                        return True
            except ValueError:
                logger.warning(f"Invalid IP/CIDR in whitelist: {allowed}")
                continue
        
        return False
    except ValueError as e:
        logger.error(f"Invalid client IP: {client_ip}, error: {e}")
        return False


def validate_callback_ip(client_ip: str, provider: str) -> bool:
    """
    验证支付回调IP是否合法
    
    Args:
        client_ip: 客户端IP地址
        provider: 支付提供商 ("wechat" 或 "alipay")
    
    Returns:
        bool: IP是否合法
    """
    if provider == "wechat":
        return validate_ip_in_whitelist(client_ip, WECHATPAY_CALLBACK_IPS)
    elif provider == "alipay":
        return validate_ip_in_whitelist(client_ip, ALIPAY_CALLBACK_IPS)
    else:
        logger.warning(f"Unknown provider: {provider}")
        return False
