class CaseDocumentParser:
    """案例文档解析器"""

    def __init__(self):
        self.chunks = []

    def parse_cases(self, cases: list[dict]) -> list[dict]:
        """解析案例列表为向量文档"""
        self.chunks = []
        for case in cases:
            case_id = case.get("id", f"case_{len(self.chunks)}")
            case_type = case.get("type", "其他")
            title = case.get("title", "")
            facts = case.get("facts", "")
            judgment = case.get("judgment", "")
            legal_basis = case.get("legal_basis", "")
            result = case.get("result", "")

            full_text = (
                f"【案件类型】{case_type}\n"
                f"【案件标题】{title}\n"
                f"【案件事实】{facts}\n"
                f"【法律依据】{legal_basis}\n"
                f"【裁判结果】{result}\n"
                f"【判决要点】{judgment}"
            )

            self.chunks.append({
                "id": case_id,
                "text": full_text,
                "metadata": {
                    "case_type": case_type,
                    "title": title,
                    "category": self._infer_category(case_type, title, facts),
                    "judgment": judgment[:100] if judgment else ""
                }
            })

        return self.chunks

    def _infer_category(self, case_type: str, title: str, facts: str) -> str:
        """推断分类"""
        text = f"{case_type} {title} {facts}"
        categories = []

        if any(kw in text for kw in ["劳动", "工资", "合同", "解除", "开除", "工伤"]):
            categories.append("劳动争议")
        if any(kw in text for kw in ["合同", "违约", "买卖", "租赁"]):
            categories.append("合同纠纷")
        if any(kw in text for kw in ["离婚", "抚养", "财产", "婚姻"]):
            categories.append("婚姻家庭")
        if any(kw in text for kw in ["侵权", "赔偿", "伤害", "医疗"]):
            categories.append("侵权责任")
        if any(kw in text for kw in ["债务", "借贷", "借款", "担保"]):
            categories.append("债权债务")

        return ", ".join(categories) if categories else "其他"


