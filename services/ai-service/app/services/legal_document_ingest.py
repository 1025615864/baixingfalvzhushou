class LegalDocumentParser:
    """法律文档解析器 - 基于语义层级的切块"""

    def __init__(self):
        self.chunks = []

    def parse_text(self, text: str, law_name: str, effective_date: str = "2021-01-01"):
        """解析法律文本为结构化块"""
        self.chunks = []
        lines = text.split('\n')
        current_chapter = ""
        current_section = ""
        current_article = ""
        current_article_num = ""
        current_content = []

        for line in lines:
            line = line.strip()
            if not line:
                continue

            chapter_match = re.match(r'^第([一二三四五六七八九十百千万]+)编\s*([^第]+)?', line)
            if chapter_match:
                current_chapter = f"第{chapter_match.group(1)}编"
                if current_article:
                    self._save_chunk(law_name, current_chapter, current_section, current_article_num, current_content, effective_date)
                current_article = ""
                current_content = []
                continue

            section_match = re.match(r'^第([一二三四五六七八九十百千万]+)章\s*([^第]+)?', line)
            if section_match:
                current_section = f"第{section_match.group(1)}章"
                if current_article:
                    self._save_chunk(law_name, current_chapter, current_section, current_article_num, current_content, effective_date)
                current_article = ""
                current_content = []
                continue

            article_match = re.match(r'^第([一二三四五六七八九十百千万\d]+)条(?:\s*(.+))$', line)
            if article_match:
                if current_article:
                    self._save_chunk(law_name, current_chapter, current_section, current_article_num, current_content, effective_date)

                current_article_num = article_match.group(1)
                current_article = article_match.group(2) if article_match.group(2) else ""
                current_content = [current_article] if current_article else []
            else:
                if current_article:
                    current_content.append(line)

        if current_article:
            self._save_chunk(law_name, current_chapter, current_section, current_article_num, current_content, effective_date)

        return self.chunks

    def _save_chunk(self, law_name: str, chapter: str, section: str, article_num: str, content: list, effective_date: str):
        """保存切块"""
        if not content:
            return

        full_text = "\n".join(content)
        chunk_id_base = f"{law_name}_{article_num}".replace(" ", "_").replace("《", "").replace("》", "").replace(":", "_")
        chunk_id = f"{chunk_id_base}_{len(self.chunks)}"

        self.chunks.append({
            "id": chunk_id,
            "text": full_text,
            "metadata": {
                "law_name": law_name,
                "chapter": chapter or "",
                "section": section or "",
                "article_num": f"第{article_num}条",
                "effective_date": effective_date,
                "category": self._infer_category(law_name, full_text)
            }
        })

    def _infer_category(self, law_name: str, text: str) -> str:
        """推断分类"""
        categories = []

        if "劳动" in law_name or "劳动合同" in text:
            categories.append("劳动")
        if "合同" in text or "民法典" in law_name:
            categories.append("合同")
        if "债务" in text or "债权" in text:
            categories.append("债权债务")
        if "婚姻" in text or "离婚" in text:
            categories.append("婚姻家庭")
        if "继承" in text:
            categories.append("继承")
        if "房产" in text or "房屋" in text:
            categories.append("房产")
        if "侵权" in text or "责任" in text:
            categories.append("侵权责任")
        if "刑事" in text or "犯罪" in text:
            categories.append("刑事")
        if "保险" in text:
            categories.append("社会保险")
        if "民事" in text or "总则" in text:
            categories.append("民法")

        return ", ".join(categories) if categories else "其他"


